import {
    addDoc, 
    collection, 
    deleteDoc, 
    doc,
    getDocs,
    query,
    serverTimestamp,
    updateDoc,      
    where
} from "firebase/firestore";

import { db } from "./config.js";      //imports the Firestore database

const calendarRef = collection(db, "calendars");   //references the calendars collection

export async function createCalendar(calendarData) {     //creates a new calendar
    const newCalendar = await addDoc(calendarRef, {     //adds a document to the collection
        ...calendarData,                       //copies the provided calendar information
        createdAt: serverTimestamp(),           //records when the calendar was created
        updatedAt: serverTimestamp()             //records when it was last updated
    });

    return newCalendar.id; //returns the id generated by Firestore
}

export async function getUserCalendars(userId) { //gets calendars belonging to a user
    const userCalendarsQuery = query(         //creates the calendar search
        calendarRef,                      //searches the calendars collection
        where("ownerId", "==", userId)    //only gets calendars owned by the user
    );

    const results = await getDocs(userCalendarsQuery); //runs the query

    return results.docs.map((calendar) => { //goes through every returned calendar
        return {
            id: calendar.id,       //includes the Firestore document id
            ...calendar.data()     //includes the stored calendar information
        };
    });
}

export function updateCalendar(calendarId, changes) {     //updates an existing calendar
    const calendar = doc(db, "calendars", calendarId);     //references the selected calendar

    return updateDoc(calendar, {           //updates the calendar document
        ...changes,                      //copies the provided changes
        updatedAt: serverTimestamp()       //records when the calendar was updated
    });
}

export function removeCalendar(calendarId) {         //deletes an existing calendar
    const calendar = doc(db, "calendars", calendarId); //references the selected calendar
    return deleteDoc(calendar);                         //deletes it from Firestore
}
